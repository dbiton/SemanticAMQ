def plot_results(results_list, folder: str):
    """
    Takes the results_list generated by the evaluation loop and creates
    separate F1-Score, Precision, and Recall plots, plus a standalone legend.
    Colors represent the Filter, and markers represent the LSH.
    """
    df = pd.DataFrame(results_list)
    
    # Split 'Config' into separate 'Filter' and 'LSH' columns
    df[['Filter', 'LSH']] = df['Config'].str.split(' + ', regex=False, expand=True)
    
    # Set styling
    sns.set_theme(style="whitegrid")
    
    # Define metrics to plot
    metrics = ['F1-Score', 'Precision', 'Recall']
    
    # 1. Create a consistent color mapping for Filters
    unique_filters = df['Filter'].unique()
    palette = sns.color_palette("husl", len(unique_filters))
    color_map = dict(zip(unique_filters, palette))
    
    # 2. Create a consistent marker mapping for LSH families
    unique_lshs = df['LSH'].unique()
    available_markers = ['o', 's', '^', 'D', 'v', '<', '>', 'p', '*', 'X']
    marker_map = dict(zip(unique_lshs, available_markers[:len(unique_lshs)]))
    
    configs = df['Config'].unique()
    
    # 3. Generate individual plots for each metric
    for metric in metrics:
        fig, ax = plt.subplots(figsize=(8, 6))
        
        sns.lineplot(
            data=df,
            x='Percentage',
            y=metric,
            hue='Filter',       # Color mapped to Filter
            style='LSH',        # Marker mapped to LSH
            markers=marker_map, # Apply specific markers
            dashes=False,       # Keep lines solid, just change markers
            palette=color_map,  # Apply specific colors
            ax=ax,
            legend=False        # Disable legend for the individual plots
        )
        
        ax.set_xlabel('Percentage of Duplicates (%)', fontsize=12)
        ax.set_ylabel(metric, fontsize=12)
        ax.set_ylim(-0.05, 1.05) # Standardize Y-axis between 0 and 1
        
        # Save each plot
        filename = f'{metric.lower().replace("-", "_")}_plot.png'
        plt.savefig(f"plots/{folder}/{filename}", bbox_inches='tight', dpi=300)
        plt.close()
        print(f"Saved plots/{folder}/{filename}")

    # 4. Generate a separate plot just for the legend
    fig_leg, ax_leg = plt.subplots(figsize=(10, 2))
    ax_leg.axis('off') # Hide axes for the legend plot
    
    # Create proxy artists for the legend reconstructing the exact combinations
    handles = []
    for config in configs:
        filt, lsh = config.split(' + ')
        handles.append(
            plt.Line2D([0], [0], color=color_map[filt], lw=2, marker=marker_map[lsh])
        )
    
    # Add legend to the blank axes
    ax_leg.legend(
        handles, 
        configs, 
        loc='center', 
        ncol=min(3, len(configs)), # Adjust columns based on number of configs
        title="Configuration (Color = Filter, Marker = LSH)",
        title_fontsize=12,
        fontsize=10,
        frameon=True
    )
    
    plt.savefig(f"plots/{folder}/legend_only.png", bbox_inches='tight', dpi=300)
    plt.close()
    print(f"Saved plots/{folder}/legend_only.png")

def calculate_distance_threshold(vectors: np.ndarray, percentage: float) -> float:
    """
    Calculate the distance threshold such that `percentage`% of all vector
    pairs are considered duplicates (i.e., closer than the threshold).

    Strategy: sample a representative subset of pairwise L2 distances and
    return the `percentage`-th percentile of that distribution.

    Args:
        vectors:    Array of shape (N, D) containing the embedding vectors.
        percentage: Target duplicate rate in [0, 100].

    Returns:
        A float distance threshold.
    """
    n = len(vectors)

    # Sampling cap: computing all N*(N-1)/2 pairs is O(N^2).
    # For large N we sample a random subset that is still statistically robust.

    # Compute pairwise squared-L2 distances via the identity
    #   ||a - b||^2 = ||a||^2 + ||b||^2 - 2 a·b
    sq_norms = np.sum(vectors ** 2, axis=1)          # (M,)
    dot      = vectors @ vectors.T                     # (M, M)
    sq_dists = sq_norms[:, None] + sq_norms[None, :] - 2 * dot

    # Numerical noise can push tiny values negative
    np.clip(sq_dists, 0, None, out=sq_dists)

    # Extract upper triangle (excluding the diagonal) to avoid self-pairs
    upper_idx  = np.triu_indices(len(vectors), k=1)
    distances  = np.sqrt(sq_dists[upper_idx])        # L2 distances

    threshold = float(np.percentile(distances, percentage))
    return threshold


def compute_actual_results(vectors: np.ndarray, distance_threshold: float) -> list[bool]:
    """
    Compute ground-truth duplicate labels using the same online logic that
    the filter uses:

        - The first vector is never a duplicate  → False
        - For each subsequent vector v, it is a duplicate if its L2 distance
          to *any* previously accepted (non-duplicate) vector is ≤ threshold.
          If it is NOT a duplicate it is added to the reference set.

    Args:
        vectors:            Array of shape (N, D).
        distance_threshold: Maximum L2 distance to be considered a duplicate.

    Returns:
        List of N booleans, one per vector.
    """
    actual_results = [False]          # first vector is never a duplicate
    reference_set  = [vectors[0]]     # accepted (unique) vectors so far

    for v in vectors[1:]:
        ref_array = np.array(reference_set)           # (R, D)
        diffs     = ref_array - v                     # (R, D)
        distances = np.sqrt(np.sum(diffs ** 2, axis=1))  # (R,)

        is_dup = bool(np.any(distances <= distance_threshold))
        actual_results.append(is_dup)

        if not is_dup:
            reference_set.append(v)

    return actual_results


def compute_static_actual_results(construct_vectors: np.ndarray, query_vectors: np.ndarray, distance_threshold: float) -> list[bool]:
    """
    Compute ground-truth duplicate labels specifically for static evaluation.
    
    A query vector is considered a duplicate ONLY if it is within the threshold 
    distance of a vector in the initial construct set. Unlike dynamic evaluation,
    new unique query vectors are NOT added to the reference set.

    Args:
        construct_vectors:  Array of shape (C, D) containing the vectors the filter was built on.
        query_vectors:      Array of shape (Q, D) containing the vectors being queried.
        distance_threshold: Maximum L2 distance to be considered a duplicate.

    Returns:
        List of Q booleans, one per query vector.
    """
    actual_results = []
    
    for v in query_vectors:
        diffs = construct_vectors - v                        # (C, D)
        distances = np.sqrt(np.sum(diffs ** 2, axis=1))      # (C,)
        
        is_dup = bool(np.any(distances <= distance_threshold))
        actual_results.append(is_dup)
        
    return actual_results


dynamic_filters = [CuckooFilter, SetFilter]#, BloomFilter]
static_filters  = [Xor8Filter, Xor16Filter, Fuse8Filter, Fuse16Filter]
lsh_families: List[LSH] = [CrossPolytopeLSH, SimHashLSH]


def static_evaluation():
    num_vectors = 1000
    dim = 384
    min_percentage_duplicates = 1
    max_percentage_duplicates = 9
    count_steps = 9
    bits = 64
    percentage_construct = 10
    max_L = 256
    memory_budget = 10 * 1024 * 1024  # 10 MB

    dataset_name = 'ELI5'
    dataset = load_embeds(dataset_name, num_vectors)
    vectors = dataset[0]
    
    split_index = int(num_vectors * percentage_construct / 100)
    vectors_construct = vectors[:split_index]
    vectors_query = vectors[split_index:]

    results_list = []
    for percentage in np.linspace(min_percentage_duplicates, max_percentage_duplicates, count_steps):
        distance_threshold = calculate_distance_threshold(vectors, percentage)

        # ── Ground-truth labels strictly for the static query set ───────────
        actual_results = compute_static_actual_results(vectors_construct, vectors_query, distance_threshold)
        # ────────────────────────────────────────────────────────────────────

        for filter_cls in static_filters + dynamic_filters:
            for lsh_cls in lsh_families:
                config_label = f"{filter_cls.__name__} + {lsh_cls.__name__}"
                print(f"Evaluating {config_label} @ {percentage:.1f}% ...")

                # Initialize LSH with varying size
                lsh_instance = lsh_cls.build_optimized(dim, distance_threshold, None, max_L)
                try:
                    filter_instance = filter_cls(dim=dim, lsh=lsh_instance, max_memory=memory_budget)
                except Exception as e:
                    print(f"Error occurred while initializing {filter_cls.__name__}: {e}")
                    filter_instance = filter_cls(dim=dim, lsh=lsh_instance)
                print(f"filter_instance: {type(filter_instance).__name__}, lsh_instance: {type(lsh_instance).__name__}")
                
                # Construct on the base set, query on the remainder
                filter_instance.construct(vectors_construct)
                predicted_results = filter_instance.query(vectors_query)

                # Now `predicted_results` and `actual_results` are both length len(vectors_query)
                tp = sum(1 for p, a in zip(predicted_results, actual_results) if     p and     a)
                fp = sum(1 for p, a in zip(predicted_results, actual_results) if     p and not a)
                fn = sum(1 for p, a in zip(predicted_results, actual_results) if not p and     a)
                tn = sum(1 for p, a in zip(predicted_results, actual_results) if not p and not a)

                fpr       = fp / (fp + tn)                    if (fp + tn) > 0 else 0
                fnr       = fn / (fn + tp)                    if (fn + tp) > 0 else 0
                precision = tp / (tp + fp)                    if (tp + fp) > 0 else 0
                recall    = tp / (tp + fn)                    if (tp + fn) > 0 else 0
                f1_score  = (2 * precision * recall
                             / (precision + recall))          if (precision + recall) > 0 else 0
                result = {
                    'Config':     config_label,
                    'Percentage': percentage,
                    'Threshold':  distance_threshold,
                    'Bits':       bits,
                    'FPR':        fpr,
                    'FNR':        fnr,
                    'Precision':  precision,
                    'Recall':     recall,
                    'F1-Score':   f1_score,
                }
                print(result)
                results_list.append(result)

    print("Evaluation completed.")
    plot_results(results_list, "static")
    return results_list


