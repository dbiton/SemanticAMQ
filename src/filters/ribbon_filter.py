"""
Ribbon Filter implementation.

Based on the 2021 paper:
"Ribbon filter: practically smaller than Bloom and Xor"
by Düll, Lang, and Lemire (arXiv:2103.02515)

A ribbon filter is an XOR-based static filter that uses a sparse linear system
over GF(2) solved via a "ribbon" construction that is more cache-friendly than
standard XOR filters.

Key properties:
- Near-optimal space efficiency (≈1.23× n for 3-arity)
- Static: elements cannot be added after construction
- FPR is precisely tunable via bits_per_key (ε = 1/2^bits_per_key)
- Query time is O(arity) = O(1) — very fast
"""

import sys
import xxhash
from collections import deque
from typing import Optional, List, Tuple
from filters.filter import Filter
from lsh import LSH


class RibbonFilter(Filter):
    """
    A Ribbon Filter: an XOR-based static filter with compact representation.

    Ribbon filters store elements by solving a system of linear equations
    over GF(2). The construction builds a sparse "ribbon" matrix where
    each element's fingerprint is the XOR of selected rows.

    This is a STATIC filter – once constructed, elements cannot be added
    or removed.

    Args:
        dim:          Dimensionality of the input vectors.
        lsh:          Pre-built LSH instance.
        bits_per_key: Number of fingerprint bits per element (8, 16, or 32).
                      Higher values yield lower FPR but use more memory.
                      Default 8 → ≈0.4% FPR.
        arity:        Number of hash functions (rows) per element. Default 3.
        max_memory:   Maximum memory usage in bytes. If set, num_slots during
                      construct() is bounded by the budget (bits_per_key is
                      fixed by the caller).
    """

    def __init__(
        self,
        dim: int,
        lsh: Optional[LSH] = None,
        bits_per_key: int = 8,
        arity: int = 3,
        max_memory: Optional[int] = None,
    ):
        super().__init__(dim, lsh, max_memory=max_memory)

        self._bits_per_key = bits_per_key
        self._arity = arity
        self._epsilon = 1.0 / (2 ** bits_per_key)
        self._constructed = False

        # Internal data (set during construct)
        self._keys: List[str] = []
        self._solution: List[int] = []
        self._num_slots: int = 0
        self._num_entries: int = 0

    def get_exact_matching_fpr(self) -> float:
        """Returns the theoretical FPR of the ribbon filter (1/2^bits_per_key)."""
        return float(self._epsilon)

    @staticmethod
    def _hash_to_row(key: str, num_slots: int, seed: int) -> int:
        """Deterministically map a key + seed to a row index using xxhash."""
        h = xxhash.xxh32(f"{key}:{seed}").intdigest()
        return h % num_slots

    @staticmethod
    def _hash_to_values(
        key: str, num_slots: int, arity: int, bits_per_key: int
    ) -> Tuple[int, List[int]]:
        """
        Map a key to its (masked) fingerprint and arity distinct row indices.

        The fingerprint is masked to bits_per_key bits and guaranteed non-zero.
        Row indices are generated by incrementing a seed until arity distinct
        slots are found.
        """
        fp_raw = xxhash.xxh32(key).intdigest()
        mask = (1 << bits_per_key) - 1
        fp = fp_raw & mask
        if fp == 0:
            fp = 1

        rows: List[int] = []
        seen: set = set()
        seed = 0
        while len(rows) < arity:
            r = RibbonFilter._hash_to_row(key, num_slots, seed)
            if r not in seen:
                seen.add(r)
                rows.append(r)
            seed += 1

        return fp, rows

    def construct(self, vectors) -> None:
        """
        Build the ribbon filter from a batch of vectors.

        Uses the peeling algorithm on the XOR hypergraph: each key maps to
        `arity` slots, and the construction finds an assignment of slot values
        such that XOR(solution[rows]) == fingerprint for every key.

        Retries with increased slot count if the hypergraph is not peelable.
        """
        if self.lsh is None:
            raise ValueError("RibbonFilter requires an LSH instance for construction.")

        hashes = self._normalize_hashes(self.lsh.hash(vectors))
        keys: List[str] = []
        for signature_keys in hashes:
            for key in signature_keys:
                keys.append(key)

        # Deduplicate: the same LSH key appearing multiple times (because many
        # vectors share the same hash bucket) produces identical equations in the
        # linear system.  Duplicate equations corrupt back-substitution because
        # two equations share the same pivot but are processed at different points
        # in the reversed peel order, overwriting the solution with partially
        # solved (zero-initialised) rows.
        keys = list(dict.fromkeys(keys))

        self._keys = keys
        self._num_entries = len(keys)

        if self._num_entries == 0:
            self._constructed = True
            self._num_slots = 0
            self._solution = []
            return

        if self.max_memory is not None:
            bits_available = self.max_memory * 8
            self._num_slots = max(
                self._num_entries,
                int(bits_available / self._bits_per_key)
            )
        else:
            # Ribbon filter: optimal size ≈ n * 1.23 for 3-arity.
            # Start at 1.30× to avoid most retries.
            self._num_slots = max(self._num_entries, int(self._num_entries * 1.30) + 1)

        max_retries = 5
        retry_multiplier = 1.5

        for _ in range(max_retries):
            if self._try_construct(keys):
                self._constructed = True
                return
            self._num_slots = int(self._num_slots * retry_multiplier) + 1

        # Final attempt with a generous allocation.
        self._num_slots = max(self._num_slots, self._num_entries * 5)
        if not self._try_construct(keys):
            # Should be unreachable in practice; fall back to trivial all-ones.
            self._num_slots = self._num_entries
            self._solution = [1] * self._num_slots

        self._constructed = True

    def _try_construct(self, keys: List[str]) -> bool:
        """Attempt to build the filter with the current _num_slots; returns success."""
        equations: List[Tuple[int, List[int]]] = []
        for key in keys:
            fp, rows = self._hash_to_values(
                key, self._num_slots, self._arity, self._bits_per_key
            )
            equations.append((fp, rows))
        return self._solve_ribbon(equations)

    def _solve_ribbon(self, equations: List[Tuple[int, List[int]]]) -> bool:
        """
        Solve the XOR filter linear system using the peeling algorithm.

        Phase 1 — Peel:
          Build a hypergraph where each equation is a hyperedge over its slot
          indices. Find a "leaf" slot (degree 1 — appears in exactly one
          equation). Use it as the pivot for that equation, remove the
          equation from all other slots, and repeat. Record the peel order.

          If the graph has a non-trivial 2-core (no leaf exists while equations
          remain unsolved) return False — the caller retries with more slots.

        Phase 2 — Back-substitute (reverse peel order):
          solution[pivot] = fingerprint XOR XOR(solution[other rows])
          This guarantees XOR(solution[rows]) == fingerprint for every key,
          so query's check  fp XOR XOR(solution[rows]) == 0  is correct.
        """
        n_slots = self._num_slots

        if not equations:
            self._solution = [0] * n_slots
            return True

        # Normalise: deduplicate rows within each equation.
        norm: List[Tuple[int, List[int]]] = []
        for fp, rows in equations:
            unique_rows = list(dict.fromkeys(rows))
            if unique_rows:
                norm.append((fp, unique_rows))

        n_eq = len(norm)

        # Phase 1: build slot → active equation mapping.
        slot_to_eqs: List[set] = [set() for _ in range(n_slots)]
        for eq_idx, (_, rows) in enumerate(norm):
            for r in rows:
                slot_to_eqs[r].add(eq_idx)

        solved_by: List[int] = [-1] * n_eq          # pivot slot per equation
        peel_order: List[Tuple[int, int]] = []       # (eq_idx, pivot_slot)
        solved_count = 0

        # Seed the queue with all degree-1 slots.
        queue: deque = deque(
            s for s in range(n_slots) if len(slot_to_eqs[s]) == 1
        )

        while queue:
            s = queue.popleft()
            active = slot_to_eqs[s]
            if len(active) != 1:
                continue  # degree changed; skip

            eq_idx = next(iter(active))
            if solved_by[eq_idx] != -1:
                continue  # equation already peeled via a different slot

            solved_by[eq_idx] = s
            peel_order.append((eq_idx, s))
            solved_count += 1

            # Remove this equation from all slots it touches.
            for r in norm[eq_idx][1]:
                slot_to_eqs[r].discard(eq_idx)
                if len(slot_to_eqs[r]) == 1:
                    queue.append(r)

        if solved_count < n_eq:
            return False  # 2-core exists; caller retries with more slots

        # Phase 2: back-substitute in reverse peel order.
        solution = [0] * n_slots
        for eq_idx, pivot in reversed(peel_order):
            fp, rows = norm[eq_idx]
            xor_val = fp
            for r in rows:
                if r != pivot:
                    xor_val ^= solution[r]
            solution[pivot] = xor_val

        self._solution = solution
        return True

    def query(self, vectors) -> List[bool]:
        """
        Query the ribbon filter for membership of the provided vectors.

        For each key, XOR its fingerprint with solution[row] for all rows.
        If the result is 0, the element is considered present.
        """
        if not self._constructed:
            raise ValueError("RibbonFilter has not been constructed.")
        if self.lsh is None:
            raise ValueError("RibbonFilter requires an LSH instance for querying.")

        if self._num_entries == 0 or self._num_slots == 0:
            return [False] * len(vectors)

        hashes = self._normalize_hashes(self.lsh.hash(vectors))
        results: List[bool] = []

        for signature_keys in hashes:
            found = False
            for key in signature_keys:
                fp, rows = self._hash_to_values(
                    key, self._num_slots, self._arity, self._bits_per_key
                )
                xor_sum = fp
                for r in rows:
                    xor_sum ^= self._solution[r]
                if xor_sum == 0:
                    found = True
                    break
            results.append(found)

        return results

    def insert(self, vectors) -> None:
        """Ribbon filters do not support dynamic insertion."""
        raise NotImplementedError(
            f"{self.__class__.__name__} does not support dynamic insertion. "
            "Ribbon filters are static. Please reconstruct with the full dataset."
        )

    def add(self, vectors) -> None:
        """Ribbon filters do not support dynamic insertion."""
        raise NotImplementedError(
            f"{self.__class__.__name__} does not support dynamic insertion. "
            "Ribbon filters are static. Please reconstruct with the full dataset."
        )

    def remove(self, vectors) -> List[bool]:
        """Ribbon filters do not support removal."""
        raise NotImplementedError(
            f"{self.__class__.__name__} does not support removal. "
            "Ribbon filters are static. Please reconstruct with the full dataset."
        )

    def get_bytesize(self) -> int:
        """
        Returns the approximate memory size in bytes of the Ribbon filter.

        The solution vector stores num_slots entries of bits_per_key bits each.
        """
        if not self._constructed:
            return 0
        solution_bytes = (self._num_slots * self._bits_per_key) // 8
        return solution_bytes + sys.getsizeof(self._solution)

    def __repr__(self) -> str:
        if not self._constructed:
            return (
                f"{self.__class__.__name__}(unconstructed, "
                f"bits_per_key={self._bits_per_key}, arity={self._arity})"
            )
        return (
            f"{self.__class__.__name__}("
            f"num_slots={self._num_slots}, "
            f"num_entries={self._num_entries}, "
            f"bits_per_key={self._bits_per_key}, "
            f"arity={self._arity}, "
            f"epsilon={self._epsilon:.6g}, "
            f"solution_bytes={self.get_bytesize()})"
        )
